#!/usr/bin/env node
// Vendor the platform-neutral slicer engine, the printer profiles and the calibration into the
// frontends (frontend-admin/src/slicer/engine and frontend-client/src/slicer/engine). The
// applications stay independent: each owns a copy and never imports from this package at runtime.
//
//   node scripts/sync-frontend.mjs [--target <dir>]   (default: both frontends)
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readProfiles, DEFAULT_PROFILES_DIR, DEFAULT_CALIBRATION_FILE } from '../src/node.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const argTarget = process.argv.indexOf('--target');
const targets = argTarget > 0
  ? [path.resolve(process.argv[argTarget + 1])]
  : ['frontend-admin', 'frontend-client'].map((app) => path.join(ROOT, '..', app, 'src', 'slicer', 'engine'));

// node-only modules are not copied
const NODE_ONLY = new Set(['node.mjs', 'parallel.mjs', 'worker.mjs']);
const header = (name) => `// GENERATED by slicer/scripts/sync-frontend.mjs from slicer/src/${name} — do not edit here.\n`;

const files = readdirSync(path.join(ROOT, 'src')).filter((f) => (f.endsWith('.mjs') || f.endsWith('.d.mts')) && !NODE_ONLY.has(f));
// profiles: one JSON bundle (without local file paths)
const profiles = readProfiles(DEFAULT_PROFILES_DIR).map(({ __file, ...p }) => p);
const synced = new Date().toISOString();
for (const target of targets) {
  if (existsSync(target)) rmSync(target, { recursive: true, force: true });
  mkdirSync(target, { recursive: true });
  for (const f of files) {
    const src = readFileSync(path.join(ROOT, 'src', f), 'utf8');
    if (/from 'node:|require\(|\bprocess\.(env|exit|argv|cwd)|\bBuffer\b/.test(src)) throw new Error(`${f} is not platform neutral`);
    writeFileSync(path.join(target, f), header(f) + src);
  }
  writeFileSync(path.join(target, 'profiles.json'), JSON.stringify(profiles));
  writeFileSync(path.join(target, 'calibration.json'), readFileSync(DEFAULT_CALIBRATION_FILE, 'utf8'));
  writeFileSync(path.join(target, 'VERSION.json'), JSON.stringify({
    source: 'slicer/src', synced, files, profiles: profiles.length,
  }, null, 2) + '\n');
  console.log(`synced ${files.length} engine modules, ${profiles.length} profiles and the calibration to ${path.relative(process.cwd(), target)}`);
}
