const catalog: Catalog = language === 'pl' ? pl : en;

export function t<K extends keyof Catalog>(key: K, ...args: Parameters<Catalog[K]>): string {
  const translate = catalog[key] as (...values: Parameters<Catalog[K]>) => string;
  return translate(...args);
}
